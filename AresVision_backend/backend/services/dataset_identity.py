"""Dataset identity vocabulary: fixed ids, strict request parsing, fingerprinting.

This module is intentionally dependency-light (standard library only). It is
imported by the HTTP layer, the training service, the command line training
entries and the SQLite migration, so it must never import torch, the database
engine or any file reading helper.
"""

from __future__ import annotations

import hashlib
import json
from typing import Any, Mapping, Optional

# Stable public registration order; immutable Earth releases never alias each other.
DATASET_IDS = ("openmars_mcd", "mcd_overview", "earth_merra2_daily_v1", "earth_merra2_daily_v2")
REGISTERED_DATASET_IDS = DATASET_IDS
MARS_DATASET_IDS = DATASET_IDS[:2]
EARTH_DATASET_ID = "earth_merra2_daily_v1"  # retained legacy identity
EARTH_DATASET_V2_ID = "earth_merra2_daily_v2"
DEFAULT_DATASET_ID = "openmars_mcd"

# Identity is always generated by the server; clients may only pick a dataset id.
SERVER_IDENTITY_FIELDS = frozenset({
    "dataset_version",
    "dataset_fingerprint",
    "dataset_identity_status",
    "dataset_snapshot",
})

IDENTITY_STATUS_LEGACY_INFERRED = "legacy_inferred"
IDENTITY_STATUS_LEGACY_UNKNOWN = "legacy_unknown"
IDENTITY_STATUS_UNVERSIONED = "unversioned"
IDENTITY_STATUS_VERIFIED = "verified"

REGISTRY_BINDING_BASIS = "server_registry"
UNVERSIONED_VERSION_STATUS = "unversioned"


class DatasetRequestError(ValueError):
    """A dataset request error carrying a stable code and HTTP status."""

    def __init__(
        self,
        code: str,
        message: str,
        status_code: int = 400,
        availability_reason: Optional[str] = None,
    ):
        super().__init__(message)
        self.code = code
        self.status_code = status_code
        # Only set for an unavailable registered dataset; never a server path.
        self.availability_reason = availability_reason


def normalize_dataset_id(value: Any) -> Optional[str]:
    """Normalize an explicit dataset id, or return None when it is not given.

    Empty strings, non strings and unknown ids are rejected; a missing dataset
    is never silently replaced by the default here.
    """
    if value is None:
        return None
    if not isinstance(value, str) or not value.strip():
        raise DatasetRequestError(
            "invalid_dataset_id", "Dataset id must be a non-empty string"
        )
    normalized = value.strip().lower()
    if normalized not in REGISTERED_DATASET_IDS:
        raise DatasetRequestError("unknown_dataset", "Unknown dataset id")
    return normalized


def resolve_dataset_id(
    dataset_id: Any,
    hyperparameters: Optional[Mapping[str, Any]] = None,
) -> str:
    """Resolve the effective dataset id of a new training request.

    Accepts exactly two client entry points: the new top level ``dataset_id``
    and the legacy ``hyperparameters.training_dataset``. Absent both, the
    historical default ``openmars_mcd`` is used.
    """
    hypers = hyperparameters or {}
    reserved = SERVER_IDENTITY_FIELDS | {"dataset_id"}
    if reserved.intersection(hypers):
        raise DatasetRequestError(
            "client_identity_not_allowed",
            "Dataset identity is generated by the server",
        )
    top_level = normalize_dataset_id(dataset_id)
    legacy = normalize_dataset_id(hypers.get("training_dataset"))
    if top_level is not None and legacy is not None and top_level != legacy:
        raise DatasetRequestError(
            "dataset_id_conflict", "dataset_id conflicts with training_dataset"
        )
    return top_level or legacy or DEFAULT_DATASET_ID


def require_training_dataset(dataset_id: Any) -> str:
    """Return a dataset id that may start a training run, else raise."""
    normalized = normalize_dataset_id(dataset_id) or DEFAULT_DATASET_ID
    if normalized not in MARS_DATASET_IDS:
        raise DatasetRequestError(
            "dataset_training_not_supported",
            "Earth training is not connected yet",
            status_code=409,
        )
    return normalized


def build_dataset_fingerprint(
    dataset_id: Optional[str],
    dataset_version: Optional[str],
    manifest_sha256: Optional[str],
    data_sha256: Optional[str],
) -> str:
    """Combine registration identity and both artifact hashes into one digest."""
    payload = {
        "dataset_id": dataset_id,
        "dataset_version": dataset_version,
        "manifest_sha256": manifest_sha256,
        "data_sha256": data_sha256,
    }
    encoded = json.dumps(
        payload, sort_keys=True, separators=(",", ":"), ensure_ascii=True
    ).encode("utf-8")
    return hashlib.sha256(encoded).hexdigest()


def build_identity_snapshot(payload: Mapping[str, Any]) -> str:
    """Serialize a task identity snapshot deterministically."""
    return json.dumps(dict(payload), sort_keys=True)


def infer_legacy_identity(raw_hyperparameters: Any) -> dict:
    """Infer dataset identity for a task created before identity columns existed.

    This is deliberately tolerant: unknown legacy values become
    ``legacy_unknown`` instead of raising, and the original hyperparameters are
    never rewritten. It must not reuse :func:`resolve_dataset_id`, which is the
    strict parser for new requests.
    """
    dataset_id: Optional[str] = None
    basis = "invalid_hyperparameters"
    try:
        parsed = json.loads(raw_hyperparameters) if raw_hyperparameters else {}
    except (TypeError, ValueError):
        parsed = None
    if isinstance(parsed, dict):
        raw = parsed.get("training_dataset")
        if raw is None or (isinstance(raw, str) and not raw.strip()):
            dataset_id, basis = DEFAULT_DATASET_ID, "historical_default"
        elif isinstance(raw, str) and raw.strip().lower() in MARS_DATASET_IDS:
            dataset_id, basis = raw.strip().lower(), "explicit_training_dataset"
        else:
            basis = "unknown_training_dataset"
    return {
        "dataset_id": dataset_id,
        "dataset_version": None,
        "dataset_fingerprint": None,
        "dataset_identity_status": (
            IDENTITY_STATUS_LEGACY_INFERRED if dataset_id else IDENTITY_STATUS_LEGACY_UNKNOWN
        ),
        "dataset_snapshot": build_identity_snapshot({
            "planet": "mars",
            "binding_basis": basis,
            "version_status": "unknown",
        }),
    }
